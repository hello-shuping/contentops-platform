# tools/polish_content.py
# 润色文案

async def polish_content(text: str, style: str = "正式") -> str:
    style_map = {
        "正式": "保留原意和长度，把口语化表达改成书面语，不扩写",
        "轻松": "保留原意和长度，把书面语改成口语化表达，可加一个短语气词，不扩写",
        "专业": "保留原意和长度，把通俗说法换成更专业的词汇，不扩写",
        "故事感": "保留原意和长度，把平铺直叙改成有画面感的一句或两句，不扩写",
        "口语化": "保留原意和长度，把书面语改成日常说话的语气，不扩写",
    }
    style_desc = style_map.get(style, style_map["正式"])

    return f"""请对以下文字进行润色，保持原意不变，且不要改变长度，不要扩写，不要添加新的内容。

风格要求：{style_desc}

原文：
{text}

只输出润色后的文字，不要加额外说明。"""